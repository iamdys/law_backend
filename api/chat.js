let backendMessages = [];
let lastDimIndex = null;

export default async function handler(req){
  if(req.method !== "POST"){
    return new Response(JSON.stringify({error:"only post"}),{status:404, headers:{"content-type":"application/json"}});
  }
  const body = await req.json();
  const {
    abGroup,
    currentStage,
    dimIndex,
    discussRound,
    caseFullText,
    userText
  } = body;

  // ========== 维度发生变化，清空大模型上下文，防止串案例 ==========
  if(lastDimIndex !== dimIndex){
    backendMessages = [];
    lastDimIndex = dimIndex;
  }

  // 取对应Prompt模板
  const key = abGroup.startsWith("A") ? `A:${currentStage}` : `B:${currentStage}`;
  let systemText = PROMPT_LIB[key];
  if(!systemText){
    return new Response(JSON.stringify({error:"prompt not found"}),{status:500, headers:{"content-type":"application/json"}});
  }

  //替换占位符
  systemText = systemText.replaceAll("{{caseFullText}}",caseFullText);
  systemText = systemText.replaceAll("{{currentStage}}",currentStage);

  // B组复盘探讨：动态追加当前复盘轮次
  if(key.startsWith("B") && currentStage === "DISCUSS"){
    systemText += `\n【当前复盘实际轮次：第${discussRound}轮，请严格执行对应步骤】`;
  }

  // 用户新消息入上下文
  backendMessages.push({"role":"user","content":userText});

  const API_KEY = process.env.API_KEY;
  const MODEL = process.env.MODEL || "doubao‑pro‑4k";

  const resp = await fetch("https://ark.cn-beijing.volces.com/api/v3/chat/completions",{
    method:"POST",
    headers:{
      "Authorization":`Bearer ${API_KEY}`,
      "Content‑Type":"application/json"
    },
    body:JSON.stringify({
      model:MODEL,
      system:systemText,
      messages:backendMessages,
      temperature:0.7,
      max_tokens:600
    })
  });

  const data = await resp.json();
  const aiContent = data.choices?.[0]?.message?.content || "AI返回异常";

  // AI回答存入后端上下文，下一轮继续继承对话
  backendMessages.push({"role":"assistant","content":aiContent});

  return new Response(JSON.stringify({aiReply:aiContent}),{
    headers:{"content‑type":"application/json"}
  });
}